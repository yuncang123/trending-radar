export type TranslationKey = keyof typeof EN;
export type Translator = (key: TranslationKey, values?: Record<string, string | number>) => string;

export function resolveLocale(preference: LanguagePreference, navigatorLanguage?: string): Locale {
  if (preference === "zh-CN" || preference === "en") return preference;
  const language = navigatorLanguage ?? (typeof navigator !== "undefined" ? navigator.language : "");
  return /^zh(?:-|$)/i.test(language) ? "zh-CN" : "en";
}

export function createTranslator(locale: Locale): Translator {
  const selected = locale === "zh-CN" ? ZH : {};
  return (key, values = {}) => {
    const template = selected[key] ?? EN[key] ?? key;
    return template.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`));
  };
}
